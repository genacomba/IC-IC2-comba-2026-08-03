#🟢 A1 — Verbo correcto
#Para cada acción, decí qué verbo HTTP corresponde y por qué: (a) ver la lista de libros, (b) agregar un libro nuevo, (c) borrar un libro, (d) cambiarle el precio a un libro, (e) reemplazar un libro entero por otro, (f) cambiarle solo la disponibilidad a un libro sin tocar el resto. Listo cuando: podés justificar cada verbo en una frase, y explicar la diferencia entre (e) y (f).

#A) GET Porque estamos pidiendo que el servidor nos devuelva los libros.
#B) POST Estamos mandando información para que se cree un recurso nuevo.
#C) DELETE Queremos eliminar un recurso existente.
#D) PATCH Estamos modificando solo una parte del libro.
#E) PUT Modificamos el libro entero.
#F) PATCH Estamos modificando una parte de un recurso.
#La diferencia entre PUT y PATCH es que PATCH modifica solo una parte del libro y PUT lo modifica entero.