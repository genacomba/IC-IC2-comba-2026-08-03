#🟢 A3 — Familias de códigos
#Los códigos de estado se agrupan por el primer dígito: 2xx, 3xx, 4xx, 5xx. Decí en una frase qué significa cada familia (sin memorizar cada código individual). Listo cuando: podés clasificar un código que no viste antes (ej. 301, 403) solo mirando el primer dígito.

#2xx) Salió bien
#3xx) Redirección: lo que pediste está en otro lado y hay que ir a buscarlo ahí
#4xx) El cliente se equivocó en algo
#5xx) El servidor se rompió (no es culpa de quien pidió)